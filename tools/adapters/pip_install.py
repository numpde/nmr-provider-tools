"""Construct the repository's pip commands and hash-locked requirements."""

from ..container_guard import require_container

require_container()

from collections.abc import Iterable
from pathlib import Path


def pip_command(python: str | Path) -> list[str]:
    """Select the target interpreter's pinned pip in isolation."""

    return [
        str(python),  # Use the target environment's interpreter
        "-I",  # Ignore PYTHON* settings and the user site
        "-B",  # Suppress bytecode writes
        "-m",  # Resolve pip within the target interpreter
        "pip",  # Use the target's approved installer
        "--isolated",  # Ignore user pip configuration and environment overrides
    ]


def bootstrap_pip_command(python: str, wheel: Path) -> list[str]:
    """Install pip by executing the private wheel's entry point."""

    return [
        python,  # Run with the current image's Python
        "-I",  # Ignore PYTHON* settings and the user site
        "-B",  # Suppress bytecode writes during bootstrap
        str(wheel / "pip"),  # Execute the authenticated pip wheel's entry point
        "--isolated",  # Ignore user pip configuration and environment overrides
        "install",  # Install the approved pip into the current image
        "--no-index",  # Keep installer bootstrap offline
        "--no-deps",  # Install the approved wheel alone
        "--no-compile",  # Omit generated bytecode from the installed files
        str(wheel),  # Install the verified private copy of the wheel
    ]


def seed_environment_pip_command(image_python: str, environment_python: Path, wheel: Path) -> list[str]:
    """Use the image's pip to install the approved wheel into a new environment."""

    return [
        *pip_command(image_python),  # Run the image's approved pip in isolation
        "--python",  # Direct installation into a different environment
        str(environment_python),  # Seed the new isolated environment
        "install",  # Install its own copy of pip
        "--no-index",  # Keep environment creation offline
        "--no-deps",  # Install the approved wheel alone
        "--no-cache-dir",  # Use the verified private wheel instead of a cache
        "--no-compile",  # Omit generated bytecode from the installed files
        str(wheel),  # Supply the exact installer wheel bytes
    ]


def build_wheel_command(python: str | Path, *, staged_source: Path, output: Path) -> list[str]:
    """Build a wheel offline from the caller's staged project."""

    return [
        *pip_command(python),  # Use the builder's pinned pip in isolation
        "wheel",  # Build a distribution without installing it
        "--disable-pip-version-check",  # Skip the pip update probe
        "--no-cache-dir",  # Avoid reading or populating pip's cache
        "--no-index",  # Skip package index lookup
        "--no-deps",  # Build only the requested project
        "--no-build-isolation",  # Use the already installed build dependencies
        "--wheel-dir",  # Select the wheel output directory
        str(output),  # Publish the wheel to the caller's output directory
        str(staged_source),  # Allow backend writes in scratch
    ]


def check_environment_command(python: str | Path) -> list[str]:
    """Check the installed environment's dependency consistency."""

    return [
        *pip_command(python),  # Use the selected environment's isolated pip
        "--no-cache-dir",  # Avoid reading or populating pip's cache
        "check",  # Check installed dependency compatibility
    ]


def hashed_requirement(name: str, version: str, sha256: str) -> str:
    """Encode one pinned requirement and its SHA-256 for pip."""

    return (
        f"{name}=={version} \\\n"
        f"    --hash=sha256:{sha256}\n"  # machine-string: pip requirements need a line continuation and an unlabeled SHA-256
    )


def resolve_locked_wheels_command(python: str | Path, lock: Path, pools: Iterable[Path], report: Path, *, constraints: Path | None) -> list[str]:
    """Build the offline dry-run command that records pip's wheel selections."""

    return [
        *pip_command(python),  # Use the worker's pinned pip in isolation
        "install",  # Invoke pip's install resolver
        "--dry-run",  # Select artifacts without installing them
        "--ignore-installed",  # Resolve the full lock even if packages are already installed
        "--quiet",  # Suppress routine resolver output
        "--disable-pip-version-check",  # Skip the pip update probe
        "--no-cache-dir",  # Select files from the supplied pools
        "--no-index",  # Resolve without contacting package indexes
        "--no-deps",  # Resolve only the explicitly locked closure
        "--require-hashes",  # Check every selected artifact against the lock
        "--only-binary=:all:",  # Accept wheels only
        *[argument for directory in pools for argument in ("--find-links", str(directory))],  # Search each admitted local pool
        *([] if constraints is None else ["--constraint", str(constraints)]),  # Restrict required wheels to their exact artifact paths
        "--report",  # Record the exact artifact selections
        str(report),  # Keep the selection report in private scratch
        "-r",  # Read versions and hashes from the lock
        str(lock),  # Use the validated snapshot of the lock
    ]


def install_locked_wheels_command(
    python: str | Path,
    lock: Path,
    pool: Path,
    report: Path,
    extra_pools: Iterable[Path],
    *,
    constraints: Path | None,
) -> list[str]:
    """Build the offline installation command that records installed wheels."""

    return [
        *pip_command(python),  # Run the target's pinned pip in isolation
        "install",  # Materialize the locked environment
        "--ignore-installed",  # Require fresh selection of every locked artifact
        "--disable-pip-version-check",  # Skip the pip update probe
        "--no-cache-dir",  # Use the supplied wheels instead of pip's cache
        "--no-index",  # Resolve only from local sources
        "--no-deps",  # Install only the explicitly locked closure
        "--only-binary=:all:",  # Reject source distributions
        "--require-hashes",  # Verify the lock hashes before installation
        "--no-compile",  # Leave Python bytecode unmaterialized
        "--report",  # Record which artifacts pip actually installed
        str(report),  # Write the evidence to the caller's report
        # Give pip a find-links entry for each admitted local pool
        *[
            argument
            for directory in (pool, *extra_pools)
            for argument in ("--find-links", str(directory))
        ],
        *([] if constraints is None else ["--constraint", str(constraints)]),  # Keep the selected artifact paths during installation
        "-r",  # Read exact versions and hashes from the lock
        str(lock),  # Select the lock for this environment
    ]
